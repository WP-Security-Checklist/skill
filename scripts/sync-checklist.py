#!/usr/bin/env python3
"""Regenerate the skill's checklist reference from the website's items*.md.

Reads the checklist files from the WP-Security-Checklist/website repository
(downloaded from GitHub by default, or from a local checkout with --website),
then writes skills/wordpress-security-checklist/references/checklist.md.

Exits with an error when:
- the locales do not share the same item IDs in the same order,
- references/checks.md does not have exactly one entry per item ID, or
- --check is given and checklist.md is out of date.

Usage:
  python3 scripts/sync-checklist.py                    # download from GitHub main
  python3 scripts/sync-checklist.py --website ../website
  python3 scripts/sync-checklist.py --check            # CI: fail if outdated
"""
from __future__ import annotations

import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFS = ROOT / "skills" / "wordpress-security-checklist" / "references"
CHECKLIST = REFS / "checklist.md"
CHECKS = REFS / "checks.md"

WEBSITE_RAW = "https://raw.githubusercontent.com/WP-Security-Checklist/website/{ref}/{path}"

LOCALES = [
    ("en", "English", "items.md", "https://wpsecuritychecklist.org/items/"),
    ("br", "Português (BR)", "items.br.md", "https://wpsecuritychecklist.org/br/items/"),
    ("es", "Español", "items.es.md", "https://wpsecuritychecklist.org/es/items/"),
    ("ja", "日本語", "items.ja.md", "https://wpsecuritychecklist.org/ja/items/"),
]

LABEL_RE = re.compile(
    r'<label><input type="checkbox" data-item-id="([^"]+)"\s*/>\s*(.+?)</label>',
    re.DOTALL,
)
SECTION_RE = re.compile(r"^##\s+(.+?)(?:<span[^>]*></span>)?\s*$", re.MULTILINE)
CHECK_ID_RE = re.compile(r"^###\s+(wsc-[a-z0-9-]+)\s*$", re.MULTILINE)


def read_source(filename: str, website: Path | None, ref: str) -> str:
    if website is not None:
        return (website / filename).read_text(encoding="utf-8")
    url = WEBSITE_RAW.format(ref=ref, path=filename)
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read().decode("utf-8")


def parse_items(raw: str) -> list[dict[str, str]]:
    if raw.startswith("---"):
        raw = raw.split("---", 2)[2]
    sections = [(m.start(), m.group(1).strip()) for m in SECTION_RE.finditer(raw)]
    items: list[dict[str, str]] = []
    for m in LABEL_RE.finditer(raw):
        iid, name = m.group(1), m.group(2)
        name = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", name)
        name = re.sub(r"\{:[^}]+\}", "", name)
        name = re.sub(r"\s+", " ", name).strip()
        section = ""
        for pos, title in sections:
            if pos < m.start():
                section = title
        items.append({"id": iid, "name": name, "section": section})
    return items


def check_locales(out: dict[str, list[dict[str, str]]]) -> list[str]:
    errors: list[str] = []
    en_ids = [row["id"] for row in out["en"]]
    for lang, rows in out.items():
        ids = [row["id"] for row in rows]
        if ids != en_ids:
            missing = sorted(set(en_ids) - set(ids))
            extra = sorted(set(ids) - set(en_ids))
            detail = f"missing {missing}, extra {extra}" if missing or extra else "different order"
            errors.append(f"{lang}: item IDs differ from en ({detail})")
    return errors


def check_checks(out: dict[str, list[dict[str, str]]]) -> list[str]:
    found = CHECK_ID_RE.findall(CHECKS.read_text(encoding="utf-8"))
    ids = [row["id"] for row in out["en"]]
    errors: list[str] = []
    dupes = sorted({i for i in found if found.count(i) > 1})
    missing = [i for i in ids if i not in found]
    extra = sorted(set(found) - set(ids))
    if dupes:
        errors.append(f"checks.md: duplicate entries {dupes}")
    if missing:
        errors.append(f"checks.md: no entry for {missing}")
    if extra:
        errors.append(f"checks.md: entries for unknown IDs {extra}")
    return errors


def render(out: dict[str, list[dict[str, str]]]) -> str:
    by_lang = {lang: {row["id"]: row for row in rows} for lang, rows in out.items()}
    lines = [
        "<!-- Generated by scripts/sync-checklist.py from the website's items*.md. Do not hand-edit. -->",
        "",
        "# WordPress Security Checklist items",
        "",
        "This is the canonical item list. Each item has a stable ID and its wording in every",
        "language the website supports. Checklist pages:",
        "",
    ]
    for lang, label, _, url in LOCALES:
        lines.append(f"- {label} (`{lang}`): {url}")
    lines.append("")
    section = None
    for row in out["en"]:
        if row["section"] != section:
            section = row["section"]
            lines += [f"## {section}", ""]
        lines.append(f"### {row['id']}")
        lines.append("")
        for lang, *_ in LOCALES:
            lines.append(f"- **{lang}:** {by_lang[lang][row['id']]['name']}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--website", type=Path, help="path to a local checkout of the website repository")
    parser.add_argument("--ref", default="main", help="website branch, tag, or commit to download (default: main)")
    parser.add_argument("--check", action="store_true", help="do not write; fail if checklist.md is out of date")
    args = parser.parse_args()

    out = {lang: parse_items(read_source(filename, args.website, args.ref)) for lang, _, filename, _ in LOCALES}
    for lang, rows in out.items():
        print(f"{lang}: {len(rows)} items")

    errors = check_locales(out)
    if errors:
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        return 1

    content = render(out)
    current = CHECKLIST.read_text(encoding="utf-8") if CHECKLIST.exists() else ""
    if args.check:
        if content != current:
            errors.append(f"{CHECKLIST.relative_to(ROOT)} is out of date; run scripts/sync-checklist.py")
    elif content != current:
        CHECKLIST.write_text(content, encoding="utf-8")
        print(f"Updated {CHECKLIST.relative_to(ROOT)}")
    else:
        print(f"{CHECKLIST.relative_to(ROOT)} is up to date")

    errors += check_checks(out)
    for err in errors:
        print(f"ERROR: {err}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
